"""SolidWorks-exported quadruped (`quadruped_3320`) constants.

The URDF/MJCF in this directory are generated by
``tools/build_a2_urdf.py`` from the SolidWorks export
``urdf/robot_a2.urdf``.  See ``docs/a2_compatibility.md`` for the full
mapping, the frame redefinition and the joint zero offsets.
"""

from pathlib import Path

import mujoco

from src import SRC_PATH
from mjlab.actuator import BuiltinPositionActuatorCfg
from mjlab.entity import EntityArticulationInfoCfg, EntityCfg
from mjlab.utils.os import update_assets
from mjlab.utils.spec_config import CollisionCfg

##
# MJCF and assets.
##

QUADRUPED_3320_XML: Path = (
  SRC_PATH / "assets" / "robots" / "quadruped_3320" / "xmls" / "quadruped_3320.xml"
)
assert QUADRUPED_3320_XML.exists()

MESH_DIR: Path = QUADRUPED_3320_XML.parent.parent / "meshes"


def get_assets(meshdir: str) -> dict[str, bytes]:
  assets: dict[str, bytes] = {}
  update_assets(assets, MESH_DIR, meshdir)
  return assets


def get_spec() -> mujoco.MjSpec:
  spec = mujoco.MjSpec.from_file(str(QUADRUPED_3320_XML))
  spec.assets = get_assets(spec.meshdir)
  return spec


##
# Actuator config.
#
# The A2 reference values are kept so the interface matches; the model is
# lighter (~9.2 kg) than a stock A2, so these are revisited if training shows
# actuator saturation (see docs/training.md).
##

# INTERFACE.md section 1 fixes the policy joint/actuator order as
#   RL -> FL -> RR -> FR, and hip -> thigh -> calf within each leg.
# The stock A2 config uses three family-wide regexes (`.*hip_.*`, ...), which
# makes MJLab emit the action vector grouped by family.  We instead declare one
# actuator per joint in the mandated order so the action vector, the MJCF joint
# order and the URDF declaration order are all identical.  The module asserts
# this at import time.
POLICY_JOINT_ORDER: tuple[str, ...] = tuple(
  f"{leg}_{family}_joint" for leg in ("RL", "FL", "RR", "FR") for family in ("hip", "thigh", "calf")
)

# stiffness, damping, effort_limit.
#
# The A2 reference values are 100/4 (hip, thigh) and 150/6 (calf); those are
# sized for a ~40 kg airframe.  This model is 9.2106 kg, so the same gains give
# roughly 4x the control bandwidth: a 50 Hz policy then cannot command smooth
# motion and instead bang-bang flips the actions every step (measured raw
# action-rate magnitude ~17, i.e. ~1.2 of the +/-3 command range per step), which
# is exactly what attempts 1-4 converged to.  Scale stiffness AND damping by the
# mass ratio (9.2106/40 ~= 0.23; rounded up to 0.3 for margin) so the closed-loop
# bandwidth is appropriate for the 5 ms physics step / 50 Hz control.
# effort_limit is a motor property and is left at the A2 value.
_GAIN_SCALE = 1.0  # attempt 5 showed softer gains made the action thrashing WORSE (raw rate 31 vs 17), so the A2 values are kept
_GAINS: dict[str, tuple[float, float, float]] = {
  "hip": (100.0 * _GAIN_SCALE, 4.0 * _GAIN_SCALE, 120.0),
  "thigh": (100.0 * _GAIN_SCALE, 4.0 * _GAIN_SCALE, 120.0),
  "calf": (150.0 * _GAIN_SCALE, 6.0 * _GAIN_SCALE, 180.0),
}

QUADRUPED_3320_ACTUATORS = tuple(
  BuiltinPositionActuatorCfg(
    target_names_expr=(f"^{name}$",),
    stiffness=_GAINS[name.split("_")[1]][0],
    damping=_GAINS[name.split("_")[1]][1],
    effort_limit=_GAINS[name.split("_")[1]][2],
    armature=0.03,
  )
  for name in POLICY_JOINT_ORDER
)

##
# Keyframes.
#
# The joint zeros were chosen (tools/build_a2_urdf.py) so that the A2 reference
# default stance is exactly reproduced; the foot contacts then sit 0.328 m below
# the base origin.
##

INIT_STATE = EntityCfg.InitialStateCfg(
  pos=(0.0, 0.0, 0.33),
  joint_pos={
    ".*thigh_joint": 0.9,
    ".*calf_joint": -1.8,
    ".*R_hip_joint": 0.1,
    ".*L_hip_joint": -0.1,
  },
  joint_vel={".*": 0.0},
)

##
# Collision config.
##

_foot_regex = "^[FR][LR]_foot_collision$"

# Disables all collisions except the feet; feet self-collisions are disabled.
FEET_ONLY_COLLISION = CollisionCfg(
  geom_names_expr=(_foot_regex,),
  contype=0,
  conaffinity=1,
  condim=3,
  priority=1,
  friction=(0.6,),
  solimp=(0.9, 0.95, 0.023),
)

# Enables all collisions except self-collisions; the feet get custom
# condim/friction/solimp.
FULL_COLLISION = CollisionCfg(
  geom_names_expr=(".*_collision",),
  condim={_foot_regex: 3, ".*_collision": 1},
  priority={_foot_regex: 1},
  friction={_foot_regex: (0.6,)},
  solimp={_foot_regex: (0.9, 0.95, 0.023)},
  contype=1,
  conaffinity=0,
)

##
# Final config.
##

QUADRUPED_3320_ARTICULATION = EntityArticulationInfoCfg(
  actuators=QUADRUPED_3320_ACTUATORS,
  soft_joint_pos_limit_factor=0.9,
)


def get_quadruped_3320_robot_cfg() -> EntityCfg:
  """Get a fresh quadruped_3320 robot configuration instance.

  Returns a new EntityCfg instance each time to avoid mutation issues when
  the config is shared across multiple places.
  """
  return EntityCfg(
    init_state=INIT_STATE,
    collisions=(FULL_COLLISION,),
    spec_fn=get_spec,
    articulation=QUADRUPED_3320_ARTICULATION,
  )


def assert_policy_order() -> None:
  """Fail loudly if the compiled model's joint/actuator order ever drifts."""
  spec = get_spec()
  joint_names = [j.name for j in spec.joints]
  assert joint_names[0] == "floating_base_joint", joint_names[:1]
  assert tuple(joint_names[1:]) == POLICY_JOINT_ORDER, (
    f"MJCF joint order does not match INTERFACE.md:\n  got      {joint_names[1:]}\n"
    f"  expected {list(POLICY_JOINT_ORDER)}"
  )


assert_policy_order()


if __name__ == "__main__":
  import mujoco.viewer as viewer

  from mjlab.entity.entity import Entity

  robot = Entity(get_quadruped_3320_robot_cfg())

  viewer.launch(robot.spec.compile())
